"""VPU arithmetic of the RTL that torch does not give: the lane-box tables, min/max ordering,
HardFloat's canonical NaN and the column sum's BF16 truncation. mxu1 is configs/fp8_mma.py and
the FP8 conversions are configs/cvt.py.

Unary BF16 tables are exhaustive outputs of the actual RTL, regenerated by
atlas.vector.NpuModelUnaryTableTest. Index and result are raw 16-bit encodings.
"""
from functools import lru_cache
from pathlib import Path
import gzip
import struct

import torch


@lru_cache(maxsize=None)
def _unary_table(name: str) -> torch.Tensor:
    data = gzip.decompress((Path(__file__).with_name('data') / f'{name}.bin.gz').read_bytes())
    assert len(data) == 65536 * 2
    return torch.tensor(struct.unpack('<65536H', data), dtype=torch.int32)


def unary(name: str, values: torch.Tensor) -> torch.Tensor:
    indices = values.contiguous().view(torch.int16).to(torch.int64) & 65535
    return _unary_table(name)[indices].to(torch.int16).view(torch.bfloat16)


def minmax(a: torch.Tensor, b: torch.Tensor, maximum: bool) -> torch.Tensor:
    """VectorParam's ordered-bit comparison (including NaN and signed zero)."""
    ar = a.contiguous().view(torch.int16).to(torch.int32) & 65535
    br = b.contiguous().view(torch.int16).to(torch.int32) & 65535
    ao = torch.where(ar & 32768 != 0, ar ^ 65535, ar ^ 32768)
    bo = torch.where(br & 32768 != 0, br ^ 65535, br ^ 32768)
    take_a = ao > bo if maximum else ao < bo
    return torch.where(take_a, ar, br).to(torch.int16).view(torch.bfloat16)


def extremum(values: torch.Tensor, dim: int, maximum: bool) -> torch.Tensor:
    """Reduce with minmax's ordering, which is total, so tree order is irrelevant."""
    raw = values.contiguous().view(torch.int16).to(torch.int32) & 65535
    ordered = torch.where(raw & 32768 != 0, raw ^ 65535, raw ^ 32768)
    index = ordered.argmax(dim, keepdim=True) if maximum else ordered.argmin(dim, keepdim=True)
    # Gather the raw bits: a BF16 gather canonicalizes NaN payloads.
    return values.contiguous().view(torch.int16).gather(dim, index).view(torch.bfloat16)


def canonical_nan(value: torch.Tensor) -> torch.Tensor:
    """HardFloat emits its default positive quiet NaN, without input payloads.

    Torch's own NaN bits depend on the CPU kernel (x86 vector code yields 0xffff).
    """
    raw = value.contiguous().view(torch.int16)
    return torch.where(torch.isnan(value), 0x7FC0, raw).to(torch.int16).view(torch.bfloat16)


def _truncated_bf16(value: torch.Tensor) -> torch.Tensor:
    """ColAddVec takes the upper 16 bits of FP32 results."""
    raw = (value.float().contiguous().view(torch.int32) >> 16).to(torch.int16)
    # Test the FP32 value: a NaN with only low payload bits truncates to infinity.
    raw = torch.where(torch.isnan(value), 0x7FC0, raw).to(torch.int16)
    return raw.view(torch.bfloat16)
