"""Generate files from the ISA table (atlas_isa.toml).

    python -m npu_model.isa.gen scala FILE   Instructions.scala for atlas-npu (src/main/scala/atlas/scalar)
    python -m npu_model.isa.gen card         the instruction table of npu_spec/06_instruction_set/README.md
    python -m npu_model.isa.gen mlir DIR     AtlasIsa.inc and rtl_bitpats.json for atlas-mlir, into DIR
"""
import argparse
import json
from pathlib import Path

from npu_model.isa.table import UNITS, Entry, Table, load, width

CARD = Path(__file__).resolve().parents[2] / "npu_spec/06_instruction_set/README.md"
BEGIN = "<!-- BEGIN generated by `python -m npu_model.isa.gen card`: do not edit -->"
END = "<!-- END generated -->"
HEADER = "Generated by `python -m npu_model.isa.gen {}` from npu_model/isa/atlas_isa.toml (npu-model).\n" \
         "Do not edit: change the table and generate again."
# Selector fields in the order of the hex label: opcode/funct3 or funct2/funct7 or imm.
LABEL_FIELDS = ("funct3", "funct2", "funct7", "imm")


def bitpat(e: Entry) -> str:
    """The entry's 32 bits, MSB first: 0 or 1 where the mask is set, ? elsewhere."""
    return "".join(str(e.match >> i & 1) if e.mask >> i & 1 else "?" for i in range(31, -1, -1))


def comment(prefix: str, text: str) -> str:
    return "\n".join(f"{prefix} {line}" for line in text.splitlines())


def instructions_scala(t: Table) -> str:
    major, minor = t.version
    pad = max(len(e.name) for e in t.entries.values())
    defs = "\n".join(f'  def {e.name:<{pad}} = BitPat("b{bitpat(e)}")' for e in t.entries.values())
    units = ",\n".join(f'    ("{e.name}", {e.name}, "{e.unit}")' for e in t.entries.values())
    return f"""{comment("//", HEADER.format("scala"))}

package atlas.scalar

import chisel3.util.BitPat

/** Atlas ISA {major}.{minor}: its version (CSR atlas.isa bits 31:24 and 23:16) and the encoding of each
 * instruction, for the decode table in IDecode.
 */
object Instructions {{
  val ISA_MAJOR = {major}
  val ISA_MINOR = {minor}

{defs}

  /** Each instruction's name, encoding and unit: {", ".join(UNITS)}. */
  val all: Seq[(String, BitPat, String)] = Seq(
{units})
}}
"""


def hex_label(t: Table, e: Entry) -> str:
    """opcode/selectors in hex, for example 33/0/20 for sub."""
    digits = [(f, (width(t.formats[e.format][f]) + 3) // 4) for f in LABEL_FIELDS if f in e.select]
    return "/".join([f"{e.opcode:02X}", *(f"{e.select[f]:0{n}X}" for f, n in digits)])


def card_table(t: Table) -> str:
    def configs(e: Entry) -> str:
        return "all" if e.configs == t.configurations else ", ".join(e.configs)

    def code(text: str) -> str:
        return "`" + text.replace("|", "\\|") + "`"

    entries = sorted(t.entries.values(), key=lambda e: (e.opcode, *(e.select.get(f, -1) for f in LABEL_FIELDS)))
    rows = [f"| {code(e.syntax)} | {e.format} | `{hex_label(t, e)}` | `{e.match:08x}` / `{e.mask:08x}` "
            f"| {e.unit} | {configs(e)} | {code(e.operation)} |" for e in entries]
    return "\n".join(["| Assembly | Fmt | Hex | Match / mask | Unit | Configs | Operation |",
                      "|---|---|---|---|---|---|---|", *rows])


def card(t: Table, text: str) -> str:
    """The green card text with its instruction table generated again."""
    head, rest = text.split(BEGIN)
    _, tail = rest.split(END)
    return f"{head}{BEGIN}\n{card_table(t)}\n{END}{tail}"


def atlas_isa_inc(t: Table) -> str:
    major, minor = t.version
    fields = "\n".join(f"ATLAS_FIELD({fmt}, {field}, {hi}, {lo}, {at})"
                       for fmt, fs in t.formats.items() for field, pieces in fs.items() for hi, lo, at in pieces)
    insns = "\n".join(f'ATLAS_INSN({e.name}, "{e.mnemonic}", {e.format}, 0x{e.match:08x}u, 0x{e.mask:08x}u)'
                      for e in t.entries.values())
    return f"""{comment("//", HEADER.format("mlir"))}
//
// Define ATLAS_FIELD or ATLAS_INSN before including this file to expand a list:
//   ATLAS_FIELD(format, field, hi, lo, at): word bits hi..lo hold the field's bits from bit at up
//   ATLAS_INSN(name, mnemonic, format, match, mask): a word w is the instruction if (w & mask) == match

#ifndef ATLAS_ISA_MAJOR
#define ATLAS_ISA_MAJOR {major}
#define ATLAS_ISA_MINOR {minor}
#endif

#ifdef ATLAS_FIELD
{fields}
#undef ATLAS_FIELD
#endif

#ifdef ATLAS_INSN
{insns}
#undef ATLAS_INSN
#endif
"""


def rtl_bitpats(t: Table) -> str:
    """The BitPat of each instruction, as atlas-mlir's variant inventory writes it (rtl_bitpat)."""
    return json.dumps({"isa": list(t.version), "source": "npu_model/isa/atlas_isa.toml",
                       "bitpats": {e.name: {"mnemonic": e.mnemonic, "rtl_bitpat": bitpat(e)}
                                   for e in t.entries.values()}}, indent=1) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="what", required=True)
    sub.add_parser("scala").add_argument("file", type=Path)
    sub.add_parser("card")
    sub.add_parser("mlir").add_argument("dir", type=Path)
    a = ap.parse_args()
    t = load()
    if a.what == "scala":
        a.file.write_text(instructions_scala(t))
    elif a.what == "card":
        CARD.write_text(card(t, CARD.read_text()))
    else:
        a.dir.mkdir(parents=True, exist_ok=True)
        (a.dir / "AtlasIsa.inc").write_text(atlas_isa_inc(t))
        (a.dir / "rtl_bitpats.json").write_text(rtl_bitpats(t))


if __name__ == "__main__":
    main()
